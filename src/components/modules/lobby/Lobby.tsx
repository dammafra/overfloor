import { useLobbyOptions } from '@hooks'
import { connect, setMyState } from '@multiplayer'
import { PLAYER } from '@schema'
import { useRoomState } from '@stores'
import { addRecentRoom, lobbyPath, type LobbyOptions } from '@utils'
import { getRoomCode, myPlayer } from 'playroomkit'
import { useEffect, useState } from 'react'
import { Redirect, useLocation } from 'wouter'
import { CameraRig } from './CameraRig'
import { Countdown } from './Countdown'
import { Players } from './Players'

export function Lobby() {
  const options = useLobbyOptions()
  return options ? <LobbyRoom {...options} /> : <Redirect to="/" replace />
}

function LobbyRoom({ id, username, practice, countdown }: LobbyOptions) {
  const [, navigate] = useLocation()

  const [connected, setConnected] = useState(false)

  const stage = useRoomState(s => s.stage)
  const players = useRoomState(s => s.players)

  useEffect(() => {
    connect({ roomCode: id, username, practice, countdown }).then(() => {
      setConnected(true)

      const code = getRoomCode()
      if (!code) return
      // suggested in the room form
      if (!practice) addRecentRoom(code)
      // a new room: its code generated by Playroom goes in the route, to share and rejoin it
      if (!id) navigate(lobbyPath({ id: code, username, practice, countdown }), { replace: true })
    })
  }, [id, username, practice, countdown, navigate])

  useEffect(() => {
    if (!connected) return

    setMyState(PLAYER.inLobby, true)

    return () => setMyState(PLAYER.inLobby, false)
  }, [connected])

  useEffect(() => {
    if (!connected || stage !== 'game') return
    if (players.some(p => p.id === myPlayer().id)) navigate('/game', { replace: true })
  }, [connected, stage, players, navigate])

  return (
    <>
      {!practice && <Countdown />}
      {!practice && <Players />}
      <CameraRig />
    </>
  )
}
